"""Lossless records and bounded incremental TCP framing.

The firmware's 36-byte header and six message kinds are validated against
fixtures generated by the original IJL/HJL libmeshmsg.so, not by this encoder.
"""
from __future__ import annotations
from dataclasses import dataclass
from enum import Enum
import struct
from .errors import FrameError, ProtocolError

MAGIC = b"TCP_WATER_MARK"
HEADER_SIZE = 36
PAYLOAD_MARKER = b"\nnokia_memsmsg_payload\n"
DEFAULT_MAX_RECORD_SIZE = 65536
PROFILE_LIMITS = {"common": 65536, "ijl": 65536, "hjl": 131072}

class Kind(str, Enum):
    LOGIN = "login"
    LOGOUT = "logout"
    REQUEST = "request"
    REPLY = "reply"
    HEARTBEAT = "heartbeat"
    HEARTBEAT_ACK = "heartbeatack"

    @property
    def native_type(self) -> int:
        return list(Kind).index(self)

    @property
    def marker(self) -> bytes:
        return b"nokia_memsmsg_" + self.value.encode("ascii") + b"\n"

def record_limit(profile: str) -> int:
    try:
        return PROFILE_LIMITS[profile.lower()]
    except (KeyError, AttributeError) as exc:
        raise ValueError("profile must be common, ijl, or hjl") from exc

def _limit(value: int) -> int:
    if type(value) is not int or not 1 <= value <= 0x7fffffff:
        raise ValueError("max_record_size must be a positive signed-32-bit integer")
    return value

def validate_url(url: str, *, allow_empty: bool = False) -> str:
    if not isinstance(url, str):
        raise ProtocolError("URL must be an ASCII string")
    if allow_empty and url == "":
        return url
    try:
        raw = url.encode("ascii")
    except UnicodeError as exc:
        raise ProtocolError("URL must be ASCII") from exc
    if not 1 <= len(raw) <= 64 or not url.startswith("tcp://") or any(c <= 32 or c == 127 for c in raw):
        raise ProtocolError("URL must be a tcp:// identity of at most 64 printable ASCII bytes")
    return url

@dataclass(frozen=True, slots=True)
class Message:
    sequence: int
    kind: Kind
    url: str
    payload: bytes

    def __post_init__(self) -> None:
        if type(self.sequence) is not int or not -0x80000000 <= self.sequence <= 0x7fffffff:
            raise ProtocolError("transport sequence must be a signed-32-bit integer")
        try:
            object.__setattr__(self, "kind", Kind(self.kind))
        except ValueError as exc:
            raise ProtocolError("unsupported message kind") from exc
        # Live server request records can have an empty URL field. This is
        # opaque record metadata; connection/login identities stay nonempty.
        validate_url(self.url, allow_empty=True)
        if not isinstance(self.payload, bytes):
            raise ProtocolError("payload must be bytes; NUL termination is explicit")

    def to_record(self, *, max_record_size: int = DEFAULT_MAX_RECORD_SIZE) -> bytes:
        raw = str(self.sequence).encode("ascii") + b"\n" + self.kind.marker + self.url.encode("ascii") + PAYLOAD_MARKER + self.payload
        if len(raw) > _limit(max_record_size):
            raise FrameError("complete record exceeds configured size limit")
        return raw

    def to_frame(self, *, max_record_size: int = DEFAULT_MAX_RECORD_SIZE) -> bytes:
        return encode_frame(self.to_record(max_record_size=max_record_size), max_record_size=max_record_size)

    @classmethod
    def from_record(cls, record: bytes, *, max_record_size: int = DEFAULT_MAX_RECORD_SIZE) -> Message:
        if not isinstance(record, bytes) or not 0 < len(record) <= _limit(max_record_size):
            raise FrameError("empty or oversized record")
        try:
            sequence, marker, remainder = record.split(b"\n", 2)
            url, payload = remainder.split(PAYLOAD_MARKER, 1)
        except ValueError as exc:
            raise ProtocolError("incomplete sequence/kind/URL/payload record") from exc
        if not sequence or len(sequence) > 11 or sequence.startswith(b"+") or not sequence.lstrip(b"-").isdigit() or sequence.count(b"-") > 1:
            raise ProtocolError("invalid decimal transport sequence")
        try:
            kind = Kind(marker.removeprefix(b"nokia_memsmsg_").decode("ascii"))
            if marker != kind.marker[:-1]:
                raise ValueError("incorrect marker")
            return cls(int(sequence), kind, url.decode("ascii"), payload)
        except (UnicodeError, ValueError) as exc:
            raise ProtocolError("invalid kind, sequence or URL") from exc

    def application(self):
        from .application import Envelope
        if self.kind not in (Kind.REQUEST, Kind.REPLY):
            raise ProtocolError("only request/reply messages carry application envelopes")
        return Envelope.from_payload(self.payload)

def encode_frame(record: bytes, *, max_record_size: int = DEFAULT_MAX_RECORD_SIZE) -> bytes:
    if not isinstance(record, bytes) or not 0 < len(record) <= _limit(max_record_size):
        raise FrameError("empty or oversized record")
    return MAGIC + bytes(32 - len(MAGIC)) + struct.pack("!I", len(record)) + record

class FrameDecoder:
    """Handles arbitrary TCP segmentation and multiple coalesced records.

    Vendor bytes15..31 may contain nonzero padding; only the terminated magic
    and network-order length have protocol meaning. Encoder padding is zero.
    """
    def __init__(self, *, max_record_size: int = DEFAULT_MAX_RECORD_SIZE):
        self.max_record_size = _limit(max_record_size)
        self._buffer = bytearray()
        self._needed: int | None = None

    @property
    def pending(self) -> bool:
        return bool(self._buffer) or self._needed is not None

    def feed(self, data: bytes) -> list[bytes]:
        self._buffer.extend(data)
        records = []
        while True:
            if self._needed is None:
                if len(self._buffer) < HEADER_SIZE:
                    break
                if self._buffer[:15] != MAGIC + b"\0":
                    raise FrameError("invalid terminated TCP_WATER_MARK")
                length = struct.unpack_from("!I", self._buffer, 32)[0]
                if not 0 < length <= self.max_record_size:
                    raise FrameError("declared record length is zero or exceeds the configured limit")
                del self._buffer[:HEADER_SIZE]
                self._needed = length
            if len(self._buffer) < self._needed:
                break
            records.append(bytes(self._buffer[:self._needed]))
            del self._buffer[:self._needed]
            self._needed = None
        return records

    def finish(self) -> None:
        if self.pending:
            raise FrameError("EOF in the middle of a frame")

    def reset(self) -> None:
        self._buffer.clear()
        self._needed = None
